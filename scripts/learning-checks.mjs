import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Chess} from '../dist/chess.js';
import {guides as allGuides} from '../dist/guides.js';
import {guides,removed,isIncluded} from '../dist/catalog.js';
import {purposes,directions,profile} from '../dist/purposes.js';
import {boardFacts,transition,checklist,explainCandidate} from '../dist/coach.js';
import {replay,parseInfo,toCandidate,collectResult} from '../dist/uci.js';
assert.equal(guides.length,49);assert.equal(removed.length,25);
assert(!isIncluded({cf:'C',hk:'—'}));assert(!isIncluded({cf:'—',hk:'Tricks Only'}));assert(!isIncluded({cf:'D',hk:'Really, Bro'}));assert(!isIncluded({cf:'—',hk:'—'}));
assert(isIncluded({cf:'C',hk:'Unbreakable'}));assert(isIncluded({cf:'S',hk:'Garbage'}));assert(isIncluded({cf:'—',hk:'Legit'}));
for(const g of guides){const p=profile(g);assert(p.focus.length>=2&&p.focus.every(id=>purposes.some(x=>x[0]===id)),g.id);assert(p.paths.length&&p.paths.every(id=>directions.some(x=>x[0]===id)),g.id);}
const italian=guides.find(g=>g.id==='italian');
assert.equal(transition(['e4','e5','Nf3','Nf6'],italian).title,'다른 갈래: 페트로프 디펜스');
assert.equal(transition(['e4','e5','Nf3'],italian).title,'대표 수순 안에서 진행 중');
assert.equal(transition(['e4','e5','Nf3','Nc6','Bc4','h6'],italian).title,'대표 수순과 다른 국면');
const c=new Chess();for(const m of ['e4','e5','Nf3','Nf6'])c.move(m);
assert.equal(boardFacts(c,'w').undeveloped.length,3);assert.equal(checklist(c,italian,'w').length,5);
assert(explainCandidate(c.fen(),'Nc3',italian,'w').text.includes('전개'));
assert.equal(replay(c.fen(),c.history()).command,'position startpos moves e2e4 e7e5 g1f3 g8f6');
assert(replay(c.fen(),['d4']).command.startsWith('position fen '));
assert.equal(parseInfo('info depth 4 score cp 30 lowerbound pv e2e4'),null);
const info=parseInfo('info depth 9 multipv 1 score cp 20 nodes 2000 pv e2e4 e7e5');
assert.equal(info.depth,9);assert.equal(info.rank,1);assert.equal(info.nodes,2000);
assert.deepEqual(toCandidate(new Chess().fen(),info).pv,['e4','e5']);
const groups=new Map([[9,new Map([[1,info]])],[8,new Map([[1,{...info,depth:8}],[2,{...info,depth:8,rank:2,uci:['d2d4','d7d5']}],[3,{...info,depth:8,rank:3,uci:['g1f3','g8f6']}]])]]);
assert.equal(collectResult(new Chess().fen(),groups,3,'e2e4').depth,8);
assert.equal(toCandidate('7k/P7/8/8/8/8/8/K7 w - - 0 1',{uci:['a7a8q'],score:0,kind:'cp'}).promotion,'q');
assert.equal(toCandidate('7k/8/8/3pP3/8/8/8/K7 w - d6 0 1',{uci:['e5d6'],score:0,kind:'cp'}).san,'exd6');
assert.equal(toCandidate('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1',{uci:['e1g1'],score:0,kind:'cp'}).san,'O-O');
assert.throws(()=>toCandidate(new Chess().fen(),{uci:['e2e5'],score:0,kind:'cp'}));
assert.equal(guides.length+removed.length,allGuides.length);
fs.mkdirSync('outputs',{recursive:true});fs.writeFileSync('outputs/learning-validation.json',JSON.stringify({kept:guides.length,excluded:removed.length,uciAndPolicyChecks:true,failures:[]},null,2));
